# %% Листинг «Первая ячейка: BookLM и число параметров» — раздел «Код и ноутбуки»
import sys
sys.path.insert(0, ".")                  # корень репозитория
import torch
from booklm.model import BookLM, BookLMConfig

torch.manual_seed(0)                     # одинаковые случайные числа у всех
cfg = BookLMConfig()                     # размеры модели
model = BookLM(cfg)
n = model.num_params()
print("слоёв, ширина, словарь:", cfg.layers, cfg.d_model, cfg.vocab)
print("параметров:", n)
print("МБ при 4 байтах на число:", round(n * 4 / 2**20, 1))
print("у GPT-3 параметров больше в", round(175e9 / n), "раз")
# Вывод в книге:
# | слоёв, ширина, словарь: 6 256 8192
# | параметров: 6622464
# | МБ при 4 байтах на число: 25.3
# | у GPT-3 параметров больше в 26425 раз

# %% Листинг «Что модель выдаёт на выходе» — раздел «Следующий токен и генерация текста»
ids = torch.tensor([[1, 517, 2048, 33, 900]])   # один текст из пяти номеров
with torch.no_grad():                           # только считаем, не учим
    scores = model(ids)
print(tuple(scores.shape))
last = scores[0, -1]                            # последняя позиция текста
top = last.topk(3)                              # три самые высокие оценки
print("лучшие номера:", top.indices.tolist())
print("их оценки:", [round(v, 2) for v in top.values.tolist()])
lo, hi = last.min().item(), last.max().item()   # крайние оценки
print("все оценки от", round(lo, 2), "до", round(hi, 2))
share = last.softmax(-1).max().item()           # доля лидера
print("доля лидера:", round(share, 5), "| поровну:", round(1 / 8192, 5))
# Вывод в книге:
# | (1, 5, 8192)
# | лучшие номера: [5937, 5586, 3970]
# | их оценки: [1.07, 1.07, 1.03]
# | все оценки от -1.06 до 1.07
# | доля лидера: 0.00034 | поровну: 0.00012

# %% Листинг «Следующий токен у обученной BookLM» — раздел «Следующий токен и генерация текста»
from booklm.lab import load, tokens, next_token_table, prompt_ids

tok, base = load("base")                  # BookLM после обучения на сказках
pieces = tokens(tok, "Сколько будет 17 умножить на 24?")
print(len(pieces), "токенов:", "|".join(piece for number, piece in pieces))
for text in ["Жила-была маленькая", "17 умножить на 24 будет", "17 умножить на 24 будет "]:
    print(f"после {text!r}:")
    for piece, p in next_token_table(tok, base, text, k=4):
        print(f"    {piece!r:14}{p:.2f}")
with torch.no_grad():
    s = base(torch.tensor([prompt_ids(tok, "Жила-была маленькая")]))[0, -1]
print("оценки от", round(s.min().item(), 2), "до", round(s.max().item(), 2))
# Вывод в книге:
# | 16 токенов: С|к|олько| будет| |1|7| ум|н|ож|ить| на| |2|4|?
# | после 'Жила-была маленькая':

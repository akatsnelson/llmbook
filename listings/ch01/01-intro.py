# %% Листинг «Жадная генерация: восемь шагов» — раздел «Следующий токен и генерация текста»
ids = torch.tensor([[1, 517, 2048, 33, 900]])
with torch.no_grad():
    for step in range(8):                              # восемь новых токенов
        best = model(ids)[0, -1].argmax()              # номер самой высокой оценки
        ids = torch.cat([ids, best.view(1, 1)], dim=1) # дописываем его в конец
print(ids.tolist())
# Вывод в книге:
# | [[1, 517, 2048, 33, 900, 5937, 5937, 5937, 5937, 5937, 5937, 5937, 5937]]

# %% Листинг «Сказка от BookLM, жадный выбор» — раздел «Следующий токен и генерация текста»
import textwrap

tok, chat = load("instruct")             # дообученная на просьбах BookLM
request = "Напиши сказку про кота, который боялся темноты."
ids = torch.tensor([prompt_ids(tok, request, chat=True)])
start = ids.shape[1]                     # здесь кончается просьба
with torch.no_grad():
    for step in range(300):
        best = chat(ids)[0, -1].argmax()               # тот же жадный шаг
        if best.item() == 2:                           # 2 -- токен <eos>
            break
        ids = torch.cat([ids, best.view(1, 1)], dim=1)
story = tok.decode(ids[0, start:].tolist())
for line in story.splitlines():
    print(textwrap.fill(line.strip(), 76))
print("токенов в ответе:", ids.shape[1] - start)

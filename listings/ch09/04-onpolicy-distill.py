# %% Листинг «Обратный KL по одному токену и по всему словарю» — раздел «Оценка по токену и по словарю»
import torch

teacher = torch.tensor([2.0, 1.0, 0.0], dtype=torch.float64)  # логиты учителя
student = torch.tensor([1.0, 1.0, 0.0], dtype=torch.float64)  # логиты ученика
lp_s, lp_t = student.log_softmax(-1), teacher.log_softmax(-1)
per_token = lp_s - lp_t                       # слагаемое для каждого токена
print("слагаемое по токену:", " ".join(f"{v:+.3f}" for v in per_token))
torch.manual_seed(0)
picks = torch.multinomial(lp_s.exp(), 10000, replacement=True)
est = per_token[picks]                        # ученик выбрал токен, учитель оценил
print(f"по одному токену: среднее {est.mean():.4f}, разброс {est.std():.4f}")
full = (lp_s.exp() * per_token).sum()         # сумма по словарю
print(f"по всему словарю: {full:.4f} на каждой позиции")
# Вывод в книге:
# | слагаемое по токену: -0.454 +0.546 +0.546
# | по одному токену: среднее 0.1255, разброс 0.4936
# | по всему словарю: 0.1233 на каждой позиции

